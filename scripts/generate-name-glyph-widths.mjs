// Measures how wide each character of the UI font is, for the seat labels.
//
// A name on a seat is fitted to its box by arithmetic, not by measuring the
// rendered text: the same layout has to come out of jsdom, of
// renderToStaticMarkup for the export and of the browser. So the advance width
// of every character a name is likely to hold is measured here once, in
// Chromium with Instrument Sans loaded from the installed @fontsource package,
// at the two weights a seat uses (400, and 700 for the projection's contrast
// mode), and written to src/data/nameGlyphWidths.json as a fraction of the
// font size. src/utils/ui/seatLabelLayout.ts reads the table.
//
// Kerning is left out: the sum of the advances is a little wider than the
// kerned text, which errs on the side of a name that fits.
//
// Usage: npm run generate:glyph-widths (after updating the font package)
// Needs Chromium for Playwright: npx playwright install chromium
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';
import { logError, logInfo } from './utils/logger.mjs';

const SOURCE = 'generate-name-glyph-widths';
const projectRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
);
const fontDir = path.join(
  projectRoot,
  'node_modules',
  '@fontsource-variable',
  'instrument-sans',
);
const outputFile = path.join(
  projectRoot,
  'src',
  'data',
  'nameGlyphWidths.json',
);

const FONT_FAMILY = 'Instrument Sans Variable';
const WEIGHTS = [400, 700];
/** Large enough that rounding to three places is exact for the table. */
const MEASURE_SIZE = 1000;

const range = (from, to) =>
  Array.from({ length: to - from + 1 }, (_, index) =>
    String.fromCodePoint(from + index),
  );

/**
 * The characters of a name: printable ASCII, Latin-1 letters, Latin
 * Extended-A (Polish, Czech, Turkish, Croatian …), the Romanian comma letters,
 * the capital sharp s and the typographic apostrophes and dash.
 */
const CHARACTERS = [
  ...range(0x20, 0x7e),
  ...range(0xc0, 0xff).filter((char) => char !== '×' && char !== '÷'),
  ...range(0x100, 0x17f),
  ...range(0x218, 0x21b),
  'ẞ',
  '‘',
  '’',
  '–',
];

/** The package's @font-face rules with the font files inlined. */
async function inlineFontFaces() {
  const css = await fs.readFile(path.join(fontDir, 'wght.css'), 'utf8');
  const urls = [...css.matchAll(/url\(\.\/([^)]+)\)/g)].map(
    (match) => match[1],
  );
  let inlined = css;
  for (const file of urls) {
    const data = await fs.readFile(path.join(fontDir, file));
    inlined = inlined.replace(
      `url(./${file})`,
      `url(data:font/woff2;base64,${data.toString('base64')})`,
    );
  }
  return inlined;
}

async function main() {
  const fontFaces = await inlineFontFaces();
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage();
    await page.setContent(
      `<!doctype html><html><head><style>${fontFaces}</style></head><body></body></html>`,
    );
    const widths = await page.evaluate(
      async ({ characters, family, weights, size }) => {
        const text = characters.join('');
        for (const weight of weights) {
          await document.fonts.load(`${weight} ${size}px '${family}'`, text);
        }
        const context = document.createElement('canvas').getContext('2d');
        const result = {};
        for (const weight of weights) {
          context.font = `${weight} ${size}px '${family}'`;
          const table = {};
          for (const character of characters) {
            const width = context.measureText(character).width / size;
            table[character] = Math.round(width * 1000) / 1000;
          }
          result[weight] = table;
        }
        return result;
      },
      {
        characters: CHARACTERS,
        family: FONT_FAMILY,
        weights: WEIGHTS,
        size: MEASURE_SIZE,
      },
    );

    // A sanity check that the font, not a fallback, was measured: in
    // Instrument Sans an "m" is far wider than an "i".
    if (!(widths[400].m > widths[400].i * 2.5)) {
      throw new Error('The measured widths do not look like Instrument Sans');
    }

    const output = {
      font: FONT_FAMILY,
      note: 'Advance widths as a fraction of the font size. Generated by scripts/generate-name-glyph-widths.mjs — do not edit by hand.',
      widths,
    };
    await fs.writeFile(outputFile, `${JSON.stringify(output, null, 2)}\n`);
    logInfo(
      `Wrote ${CHARACTERS.length} characters × ${WEIGHTS.length} weights`,
      { file: path.relative(projectRoot, outputFile) },
      SOURCE,
    );
  } finally {
    await browser.close();
  }
}

main().catch((error) => {
  logError(
    'Measuring the glyph widths failed',
    { error: String(error) },
    SOURCE,
  );
  process.exitCode = 1;
});
